/**
 * The level classifier's five features, pinned against the notebook that trained on them.
 *
 *   npm run test:features:level
 *
 * WHY THIS SUITE EXISTS
 * `Run.getLevelFeatures` has to compute exactly what RunLeague_Fitness_Plan_AI.ipynb computed
 * when the forest was trained. If it does not, nothing breaks in a way anyone can see: the
 * backend hands the model a point from a slightly different space, and the model returns a
 * confident level for it. No error, no log line, no failed request — just wrong levels, and
 * therefore wrong training plans, for every runner.
 *
 * That is not a theoretical risk. It had already happened. The first version of
 * getLevelFeatures computed `avg_pace` as total time over total distance, while the notebook
 * uses the mean of each run's pace. On a history of mixed distances those differ by about
 * 12% — on a feature the forest splits on — and nothing in the system would ever have
 * reported it.
 *
 * HOW IT IS PINNED
 * tests/fixtures/level_features.golden.json holds run histories together with the feature
 * values the NOTEBOOK'S OWN pandas expressions produce for them. Those expected values were
 * generated by running the notebook's code, not by reimplementing it here — a test that
 * reimplements the thing it is checking proves only that someone wrote the same bug twice.
 * This suite replays each history through the real database and the real query, and requires
 * the answers to match.
 *
 * Needs a database it can write to. Skips cleanly without one rather than failing.
 */
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const GOLDEN = path.join(HERE, 'fixtures', 'level_features.golden.json');

let passed = 0;
const failures = [];
const ok = (label, cond, detail = '') => {
  if (cond) { passed += 1; console.log(`  ok   ${label}`); }
  else { failures.push(label); console.log(`  FAIL ${label}${detail ? `\n       ${detail}` : ''}`); }
};

const HOST = process.env.DB_HOST || 'localhost';
const PORT = process.env.DB_PORT || '5432';
const USER = process.env.DB_USER || process.env.PGUSER || 'postgres';
const PASSWORD = process.env.DB_PASSWORD || process.env.PGPASSWORD || '';
const DATABASE = process.env.DB_NAME || process.env.TEST_DB || 'run_league_verify';

async function main() {
  if (!existsSync(GOLDEN)) {
    ok('the golden fixture is present', false, `expected ${GOLDEN}`);
    return;
  }
  const { startedAt, cases } = JSON.parse(readFileSync(GOLDEN, 'utf8'));

  // This suite INSERTS users and runs and then deletes them. That is fine in a test
  // database and not fine in the one the app uses, so it refuses to run against a database
  // whose name does not look like a test one. `run_league` and `run_league_test` differ by
  // five characters, and the cost of getting it wrong is rows appearing and disappearing in
  // real data. ALLOW_NON_TEST_DB=1 overrides it for anyone who really means it.
  if (!/test|verify|demo/i.test(DATABASE) && process.env.ALLOW_NON_TEST_DB !== '1') {
    console.error(`\n  Refusing to run against "${DATABASE}" — this suite creates and deletes`);
    console.error('  users and runs, and that name does not look like a test database.');
    console.error('      $env:TEST_DB = "run_league_test"');
    console.error('  (or set ALLOW_NON_TEST_DB=1 if you are sure).\n');
    // No pool to close: this runs before either connection is opened, which is the point —
    // refuse before touching the database, not after.
    ok('the target database is a test database', false, `refused to write to "${DATABASE}"`);
    return;
  }

  // The entity has its own connection pool, built from the environment at module load and
  // pointed wherever .env says — which on a normal machine is the APP's database, not the
  // test one. So the suite has to force them together before importing it.
  //
  // Without this the test inserts its runs into TEST_DB and then asks getLevelFeatures about
  // those user ids in a DIFFERENT database, where the same ids belong to unrelated people.
  // It does not error; it returns somebody else's features, and the failures read as though
  // the query is wrong rather than as though it is answering about the wrong database. (And
  // on a machine where .env happens to point at the same database, as a sandbox's often
  // does, the whole problem is invisible.)
  //
  // DATABASE_URL is emptied rather than deleted because dotenv.config() runs inside
  // config/db.js and will happily fill a key back in from .env if it is absent — but it
  // leaves one alone that is already present, even when empty.
  process.env.DATABASE_URL = '';
  process.env.DB_NAME = DATABASE;
  const { default: Run } = await import('../entities/Run.js');
  const pool = new pg.Pool({ host: HOST, port: PORT, user: USER, password: PASSWORD, database: DATABASE });

  try {
    await pool.query('SELECT 1');
  } catch (err) {
    // Two very different problems arrive here and the old message blurred them: the server
    // being unreachable, and the server being fine but this database not existing. The
    // second is the common one — every suite defaults to `run_league_verify` while SETUP.md
    // has you create `run_league_test` — and it is fixed by naming the right database, which
    // the message now says and, where it can, lists.
    const missingDatabase = /does not exist/i.test(err.message);
    console.error(`\n  Could not use the database "${DATABASE}" — ${err.message}`);

    if (missingDatabase) {
      // Ask the server which databases DO exist. Far more useful than telling someone to go
      // and look, and it costs one query on a connection we already know works.
      let available = [];
      try {
        const admin = new pg.Pool({ host: HOST, port: PORT, user: USER, password: PASSWORD, database: 'postgres' });
        const { rows } = await admin.query(
          `SELECT datname FROM pg_database WHERE NOT datistemplate AND datname <> 'postgres' ORDER BY datname`
        );
        available = rows.map((r) => r.datname);
        await admin.end().catch(() => {});
      } catch { /* the listing is a courtesy; its absence is not another failure */ }

      if (available.length) {
        // Suggest deliberately rather than alphabetically: the project's own test databases
        // first, then anything that looks like a test database, and only then give up and
        // name the first one. Picking by sort order suggested `cred_test` on a machine with
        // leftover databases, which is advice nobody should follow.
        const preferred =
          available.find((d) => d === 'run_league_test')
          ?? available.find((d) => d === 'run_league_verify')
          ?? available.find((d) => /^run_league.*(test|verify)/.test(d))
          ?? available.find((d) => /test|verify/.test(d));

        const shown = available.length > 12 ? `${available.slice(0, 12).join(', ')} … (+${available.length - 12} more)` : available.join(', ');
        console.error(`\n  Databases on this server: ${shown}`);
        if (preferred) {
          console.error('  Point the suite at your TEST database (never the one the app uses):');
          console.error(`      $env:TEST_DB = "${preferred}"`);
        } else {
          console.error('  None of these looks like a test database. SETUP.md, "Group B — on an');
          console.error('  empty test database", has the two commands to make one.');
        }
      } else {
        console.error('\n  Create a test database first — SETUP.md, "Group B — on an empty test database".');
      }
    } else {
      console.error('\n  Check PostgreSQL is running, and that DB_USER / DB_PASSWORD are set.');
    }
    console.error('');

    await pool.end().catch(() => {});
    ok('a database was reachable', false, 'this suite cannot verify the query without one');
    return;
  }

  // Prove both connections reach the SAME database before trusting a single result.
  //
  // This suite writes through its own pool and reads through the entity's, and those are
  // configured separately — the entity's comes from .env. When they disagree the failures
  // are deeply misleading: the inserts land in one database and the queries answer about the
  // same user ids in another, so you get a mix of nulls and other people's numbers, and it
  // all reads as though the query under test is broken. Checking costs one round trip and
  // turns an hour of confusion into one line.
  const { default: appPool } = await import('../config/db.js');
  let testDb;
  let entityDb;
  try {
    testDb = (await pool.query('SELECT current_database() AS db')).rows[0].db;
    entityDb = (await appPool.query('SELECT current_database() AS db')).rows[0].db;
  } catch (err) {
    ok('both connections could be identified', false, err.message);
    await pool.end().catch(() => {});
    return;
  }

  console.log(`\n  writing to "${testDb}", reading through the entity from "${entityDb}"`);
  if (testDb !== entityDb) {
    console.error(`\n  Those are different databases, so nothing below would mean anything.`);
    console.error('  The entity takes its connection from .env — DATABASE_URL first, then DB_NAME.');
    console.error(`  Set .env's DB_NAME to "${testDb}" (and clear DATABASE_URL) while you run this.\n`);
    ok('the test and the entity use the same database', false,
      `test pool on "${testDb}", entity pool on "${entityDb}"`);
    await pool.end().catch(() => {});
    return;
  }
  ok('the test and the entity use the same database', true);

  const stamp = Date.now();
  const created = [];

  try {
    console.log('\n━━━ THE QUERY REPRODUCES THE NOTEBOOK ━━━');

    for (const [index, testCase] of cases.entries()) {
      const email = `levelfeat.${stamp}.${index}@example.com`;
      const user = await pool.query(
        `INSERT INTO users (email, password_hash, name, role)
         VALUES ($1, 'x', $2, 'registered_user') RETURNING user_id`,
        [email, `Level Feat ${index}`]
      );
      const userId = user.rows[0].user_id;
      created.push(userId);

      const base = new Date(startedAt).getTime();
      for (const run of testCase.runs) {
        await pool.query(
          `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
           VALUES ($1, $2, $3, $4)`,
          [userId, run.distanceKm, run.durationSeconds,
            new Date(base + run.offsetDays * 86400000).toISOString()]
        );
      }

      const got = await Run.getLevelFeatures(userId);
      const want = testCase.expected;

      if (!got) {
        ok(`${testCase.name}: features computed`, false, 'getLevelFeatures returned null');
        continue;
      }

      // Tolerance is for float formatting only. These are the same arithmetic on the same
      // numbers, so anything above this is a difference in definition, not in precision.
      const tolerance = 1e-6;
      const wrong = Object.keys(want).filter((key) => Math.abs(got[key] - want[key]) > tolerance);

      ok(`${testCase.name} (${testCase.runs.length} runs, ${testCase.activeWeeks} active weeks)`,
        wrong.length === 0,
        wrong.map((key) => `${key}: got ${got[key]}, notebook says ${want[key]}`).join('\n       '));
    }

    console.log('\n━━━ THE DEFINITIONS THAT ARE EASY TO GET WRONG ━━━');
    {
      // avg_pace must be the mean of per-run paces, NOT total time over total distance.
      // Built so the two answers are far apart: one long slow run, several short fast ones.
      const email = `levelpace.${stamp}@example.com`;
      const user = await pool.query(
        `INSERT INTO users (email, password_hash, name, role)
         VALUES ($1, 'x', 'Pace Shape', 'registered_user') RETURNING user_id`, [email]);
      const userId = user.rows[0].user_id;
      created.push(userId);

      const runs = [[20, 7.2], [5, 5.4], [3, 5.0], [18, 7.0], [4, 5.2]];
      const base = new Date(startedAt).getTime();
      for (const [index, [km, pace]] of runs.entries()) {
        await pool.query(
          `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
           VALUES ($1, $2, $3, $4)`,
          [userId, km, Math.round(km * pace * 60), new Date(base + index * 86400000).toISOString()]
        );
      }

      const meanOfPaces = runs.reduce((sum, [, pace]) => sum + pace, 0) / runs.length;
      const totalOverTotal =
        runs.reduce((sum, [km, pace]) => sum + km * pace, 0) / runs.reduce((sum, [km]) => sum + km, 0);

      const got = await Run.getLevelFeatures(userId);
      ok('avg_pace is the mean of the per-run paces',
        Math.abs(got.avg_pace - meanOfPaces) < 1e-6,
        `got ${got.avg_pace.toFixed(4)}, expected ${meanOfPaces.toFixed(4)}`);
      ok('and is NOT total time over total distance',
        Math.abs(got.avg_pace - totalOverTotal) > 0.5,
        `the two are ${Math.abs(meanOfPaces - totalOverTotal).toFixed(3)} min/km apart here — ` +
        'this check is what catches that substitution');

      // active_weeks counts weeks with runs in them, not weeks elapsed.
      const quietEmail = `levelquiet.${stamp}@example.com`;
      const quiet = await pool.query(
        `INSERT INTO users (email, password_hash, name, role)
         VALUES ($1, 'x', 'Two Weeks Apart', 'registered_user') RETURNING user_id`, [quietEmail]);
      const quietId = quiet.rows[0].user_id;
      created.push(quietId);
      // Two runs, 10 weeks apart: 2 active weeks, not 11.
      for (const offset of [0, 70]) {
        await pool.query(
          `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
           VALUES ($1, 10, 3600, $2)`,
          [quietId, new Date(base + offset * 86400000).toISOString()]
        );
      }
      const quietFeatures = await Run.getLevelFeatures(quietId);
      if (!quietFeatures) {
        ok('features were computed for the two-runs-apart user', false,
          'getLevelFeatures returned null for a user that definitely has runs — ' +
          'the usual cause is the entity reading a different database than this suite wrote to');
        throw new Error('cannot continue without features');
      }
      ok('active weeks counts weeks that contain runs, not weeks elapsed',
        Math.abs(quietFeatures.weekly_km - 10) < 1e-6,
        `weekly_km ${quietFeatures.weekly_km.toFixed(3)} — 20 km over 2 active weeks is 10, ` +
        'over 11 elapsed weeks it would be 1.8');
      ok('and runs_per_week likewise',
        Math.abs(quietFeatures.runs_per_week - 1) < 1e-6,
        `got ${quietFeatures.runs_per_week}`);

      // tenure truncates to whole days before dividing, as pandas' .dt.days does.
      ok('tenure_months is whole days / 30.44',
        Math.abs(quietFeatures.tenure_months - 70 / 30.44) < 1e-6,
        `got ${quietFeatures.tenure_months}`);

      // The PART-DAY case, which is the only one that can tell flooring from not flooring.
      // Every other fixture here has runs at whole-day offsets, so Math.floor is a no-op on
      // them — verified by reverting it, which passed the whole suite until this check
      // existed. Real runs happen at a time of day, so the gap is almost never whole.
      const partEmail = `levelpartday.${stamp}@example.com`;
      const part = await pool.query(
        `INSERT INTO users (email, password_hash, name, role)
         VALUES ($1, 'x', 'Part Day', 'registered_user') RETURNING user_id`, [partEmail]);
      const partId = part.rows[0].user_id;
      created.push(partId);
      // 06:00 on day 0, 18:00 on day 70 — a gap of 70.5 days.
      await pool.query(
        `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
         VALUES ($1, 10, 3600, $2)`, [partId, new Date(base).toISOString()]);
      await pool.query(
        `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
         VALUES ($1, 10, 3600, $2)`,
        [partId, new Date(base + 70 * 86400000 + 12 * 3600000).toISOString()]);

      const partFeatures = await Run.getLevelFeatures(partId);
      ok('a part-day gap is floored to whole days, as pandas does',
        Math.abs(partFeatures.tenure_months - 70 / 30.44) < 1e-9,
        `got ${partFeatures.tenure_months}, flooring gives ${(70 / 30.44).toFixed(6)}, ` +
        `keeping the fraction would give ${(70.5 / 30.44).toFixed(6)}`);
      ok('and that is measurably different from keeping the fraction',
        Math.abs(70 / 30.44 - 70.5 / 30.44) > 1e-3,
        'otherwise the check above would pass either way');
    }

    console.log('\n━━━ TOO LITTLE HISTORY ━━━');
    {
      const email = `levelempty.${stamp}@example.com`;
      const user = await pool.query(
        `INSERT INTO users (email, password_hash, name, role)
         VALUES ($1, 'x', 'No Runs', 'registered_user') RETURNING user_id`, [email]);
      const userId = user.rows[0].user_id;
      created.push(userId);

      ok('a runner with no runs gives null, not zeros',
        (await Run.getLevelFeatures(userId)) === null,
        'zeros would be scored by the model as if they were real');

      // A run with no distance cannot produce a pace, so it must not reach the model.
      await pool.query(
        `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
         VALUES ($1, 0, 600, $2)`, [userId, new Date(startedAt).toISOString()]);
      ok('a zero-distance run does not count as history',
        (await Run.getLevelFeatures(userId)) === null);

      await pool.query(
        `INSERT INTO runs (user_id, distance_km, duration_seconds, started_at)
         VALUES ($1, 5, 1800, $2)`, [userId, new Date(startedAt).toISOString()]);
      const features = await Run.getLevelFeatures(userId);
      ok('one real run is enough to compute features', features !== null);
      ok('and the zero-distance run is excluded from them',
        features.runs_per_week === 1 && Math.abs(features.weekly_km - 5) < 1e-6,
        JSON.stringify(features));
      ok('every feature is a finite number',
        Object.values(features).every((v) => Number.isFinite(v)),
        JSON.stringify(features));
    }
  } finally {
    if (created.length) {
      await pool.query('DELETE FROM runs WHERE user_id = ANY($1)', [created]).catch(() => {});
      await pool.query('DELETE FROM users WHERE user_id = ANY($1)', [created]).catch(() => {});
    }
    await pool.end().catch(() => {});
  }
}

main()
  .then(() => {
    console.log(`\n${'─'.repeat(70)}`);
    if (failures.length === 0) console.log(`  ${passed} checks passed, 0 failed`);
    else {
      console.log(`  ${passed} passed, ${failures.length} FAILED`);
      for (const f of failures) console.log(`    - ${f}`);
    }
    console.log(`${'─'.repeat(70)}\n`);
    process.exit(failures.length > 0 ? 1 : 0);
  })
  .catch((err) => {
    console.error('\n  the suite itself failed:', err.message, '\n');
    process.exit(1);
  });
